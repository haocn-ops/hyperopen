import { test } from "node:test";
import assert from "node:assert/strict";
import { join } from "node:path";

import {
  nodeModulesUsable,
  mainCheckoutNodeModules
} from "./ensure_node_modules.mjs";

test("nodeModulesUsable requires both node_modules and the shadow-cljs bin", () => {
  const present = new Set(["node_modules", join("node_modules", ".bin", "shadow-cljs")]);
  assert.equal(nodeModulesUsable((p) => present.has(p)), true);
});

test("nodeModulesUsable is false when the shadow-cljs bin is missing", () => {
  const present = new Set(["node_modules"]);
  assert.equal(nodeModulesUsable((p) => present.has(p)), false);
});

test("nodeModulesUsable is false when node_modules is absent", () => {
  assert.equal(nodeModulesUsable(() => false), false);
});

test("mainCheckoutNodeModules resolves the parent of the git common dir", () => {
  const commonDir = "/repo/.git";
  const expected = join("/repo", "node_modules");
  const present = new Set([join(expected, ".bin", "shadow-cljs")]);
  assert.equal(
    mainCheckoutNodeModules(commonDir, "/repo/.claude/worktrees/x", (p) => present.has(p)),
    expected
  );
});

test("mainCheckoutNodeModules resolves a relative common dir against cwd", () => {
  const expected = join("/repo", "node_modules");
  const present = new Set([join(expected, ".bin", "shadow-cljs")]);
  assert.equal(
    mainCheckoutNodeModules(".git", "/repo", (p) => present.has(p)),
    expected
  );
});

test("mainCheckoutNodeModules returns null when the source bin does not exist", () => {
  assert.equal(mainCheckoutNodeModules("/repo/.git", "/repo", () => false), null);
});

test("mainCheckoutNodeModules returns null without a git common dir", () => {
  assert.equal(mainCheckoutNodeModules(null, "/repo", () => true), null);
});

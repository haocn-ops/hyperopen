#!/usr/bin/env node
// Ensure a usable node_modules exists in the current (possibly worktree) checkout.
//
// A fresh `git worktree` does NOT inherit node_modules, and shadow-cljs is a
// local-only binary (resolved via npx from ./node_modules/.bin). Without it,
// every npm-based gate (`npm test`, `npm run test:websocket`, the compiles in
// `npm run check`) fails with an opaque "command not found" / "Cannot find
// module" error that LOOKS like a code defect. This script makes that failure
// mode self-healing (symlink from the main checkout) or, failing that, loud and
// actionable -- so an environmental problem never masquerades as a code bug.
//
// Strategy: if node_modules is already usable, exit 0. Otherwise locate the main
// worktree's node_modules via `git rev-parse --git-common-dir` and symlink it.
// If that is not possible, print the exact remediation command and exit 1.

import { existsSync, lstatSync, symlinkSync, unlinkSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, isAbsolute, join, resolve } from "node:path";

const SENTINEL = join("node_modules", ".bin", "shadow-cljs");

// Exported for unit testing the pure decision logic.
export function nodeModulesUsable(existsFn = existsSync) {
  return existsFn("node_modules") && existsFn(SENTINEL);
}

// Resolve the main checkout's node_modules from the git common dir.
// Returns an absolute path string, or null when it cannot be determined.
export function mainCheckoutNodeModules(
  gitCommonDir,
  cwd = process.cwd(),
  existsFn = existsSync
) {
  if (!gitCommonDir) return null;
  const commonDir = isAbsolute(gitCommonDir)
    ? gitCommonDir
    : resolve(cwd, gitCommonDir);
  // commonDir is <mainRoot>/.git ; its parent is the main checkout root.
  const mainRoot = dirname(commonDir);
  const candidate = join(mainRoot, "node_modules");
  return existsFn(join(candidate, ".bin", "shadow-cljs")) ? candidate : null;
}

function gitCommonDir() {
  try {
    return execFileSync(
      "git",
      ["rev-parse", "--path-format=absolute", "--git-common-dir"],
      { encoding: "utf8" }
    ).trim();
  } catch {
    try {
      // Older git without --path-format: resolve the relative result.
      return execFileSync("git", ["rev-parse", "--git-common-dir"], {
        encoding: "utf8"
      }).trim();
    } catch {
      return null;
    }
  }
}

function main() {
  if (nodeModulesUsable()) {
    console.log("[setup:worktree] node_modules present (shadow-cljs resolvable).");
    return 0;
  }

  const source = mainCheckoutNodeModules(gitCommonDir());
  if (source) {
    // Clean up a dangling/broken node_modules symlink if one exists.
    if (existsSync("node_modules") === false) {
      try {
        if (lstatSync("node_modules").isSymbolicLink()) unlinkSync("node_modules");
      } catch {
        // node_modules genuinely absent; nothing to clean.
      }
    }
    if (!existsSync("node_modules")) {
      symlinkSync(source, "node_modules");
      console.log(`[setup:worktree] linked node_modules -> ${source}`);
      if (nodeModulesUsable()) return 0;
    }
  }

  console.error(
    [
      "[setup:worktree] node_modules is missing or unusable and could not be linked automatically.",
      "  This is an ENVIRONMENT problem, not a code defect.",
      "  Fix it with one of:",
      "    npm ci                       # from the repo root",
      "    ln -s ../../../node_modules node_modules   # from a .claude/worktrees/<name> dir"
    ].join("\n")
  );
  return 1;
}

// Only run when invoked directly (not when imported by tests).
if (import.meta.url === `file://${process.argv[1]}`) {
  process.exit(main());
}
